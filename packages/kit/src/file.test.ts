import { ast } from '@kubb/ast'
import { type Config, Diagnostics, type Memo, withContext } from '@kubb/core'
import { describe, expect, it } from 'vitest'
import { file, type FileContext, resolveFile } from './file.ts'
import { slot } from './composables.ts'
import { Resolver } from './resolver/Resolver.ts'

function createMemo(): Memo {
  const store = new Map<string, unknown>()
  const memo = (key: string, compute: () => unknown) => {
    if (!store.has(key)) store.set(key, compute())
    return store.get(key)
  }
  return Object.assign(memo, {
    get: (key: string) => store.get(key),
    set: (key: string, value: unknown) => store.set(key, value),
    has: (key: string) => store.has(key),
  }) as Memo
}

const config = { input: 'petStore.yaml', output: { path: 'src/gen', defaultBanner: 'simple' } } as unknown as Config
const point = ast.factory.createSchema({ type: 'object', name: 'Point', properties: [] })
const pointOperation = ast.factory.createOperation({ operationId: 'point', method: 'GET', path: '/point', tags: ['geo'] })
const listPets = ast.factory.createOperation({ operationId: 'listPets', method: 'GET', path: '/pets', tags: ['pets'] })

function createContext(overrides: Partial<FileContext> = {}): FileContext {
  const resolvers: Record<string, Resolver> = { 'plugin-ts': new Resolver({ pluginName: 'plugin-ts' }) }
  const plugins: Record<string, unknown> = {
    'plugin-ts': {
      options: {
        output: { path: 'types', mode: 'directory' },
        override: [{ type: 'tag', pattern: 'geo', options: { output: { path: 'geo', mode: 'directory' } } }],
      },
    },
  }
  return {
    config,
    meta: { title: 'Pet Store', version: '1.0.0' },
    memo: createMemo(),
    schemas: [point],
    root: '/root/src/gen',
    plugin: { name: 'plugin-zod' },
    resolver: new Resolver({ pluginName: 'plugin-zod' }),
    options: { output: { path: 'zod', mode: 'directory' }, group: undefined },
    getResolver: (name: string) => resolvers[name]!,
    requirePlugin: (name: string) => {
      if (!plugins[name]) throw new Error(`Plugin "${name}" not found`)
      return plugins[name]
    },
    ...overrides,
  } as unknown as FileContext
}

describe('file', () => {
  it('resolves a schema file with the default banner and no footer', () => {
    const target = resolveFile(createContext(), point)

    expect(target.baseName).toBe('point.ts')
    expect(target.path).toBe('/root/src/gen/zod/point.ts')
    expect(target.banner).toContain('Generated by Kubb')
    expect(target.footer).toBeNull()
  })

  it('adds an Operation suffix when an operation would land on a schema file', () => {
    expect(resolveFile(createContext(), pointOperation).baseName).toBe('pointOperation.ts')
    expect(resolveFile(createContext(), listPets).baseName).toBe('listPets.ts')
  })

  it('keeps the operation name for a plugin without schema generators, by its plugin name rather than its resolver name', () => {
    const ctx = createContext({ plugin: { name: 'plugin-fetch' } as FileContext['plugin'], resolver: new Resolver({ pluginName: 'plugin-client' }) })
    ctx.memo.set(slot.templates('plugin-fetch'), [{ name: 'client', kind: 'Operation', render: () => null }])

    expect(resolveFile(ctx, pointOperation).baseName).toBe('point.ts')
  })

  it('keeps the operation path in a single-file output', () => {
    const ctx = createContext({ options: { output: { path: 'zod.ts', mode: 'single' } } } as Partial<FileContext>)

    expect(resolveFile(ctx, pointOperation).path).toBe(resolveFile(ctx, point).path)
  })

  it('resolves another plugin file with that plugin resolver and output', () => {
    const target = resolveFile(createContext(), listPets, { plugin: 'plugin-ts' })

    expect(target.path).toBe('/root/src/gen/types/listPets.ts')
  })

  it("applies the other plugin's override for the node", () => {
    const getArea = ast.factory.createOperation({ operationId: 'getArea', method: 'GET', path: '/area', tags: ['geo'] })

    expect(resolveFile(createContext(), getArea, { plugin: 'plugin-ts' }).path).toBe('/root/src/gen/geo/getArea.ts')
  })

  it('throws when the other plugin is missing', () => {
    expect(() => resolveFile(createContext(), listPets, { plugin: 'plugin-faker' })).toThrow('plugin-faker')
  })

  it('resolves operations with the same name into their own tag folders', () => {
    const ctx = createContext({ options: { output: { path: 'zod', mode: 'directory' }, group: { type: 'tag' } } } as Partial<FileContext>)
    const listStores = ast.factory.createOperation({ operationId: 'listStores', method: 'GET', path: '/stores', tags: ['stores'] })

    expect(resolveFile(ctx, listPets, { name: 'index' }).path).not.toBe(resolveFile(ctx, listStores, { name: 'index' }).path)
  })

  it('checks schema files in the location of each call', () => {
    const ctx = createContext()
    const shapePoint = ast.factory.createOperation({ operationId: 'point', method: 'GET', path: '/shapes/point', tags: ['shapes'] })
    resolveFile(ctx, pointOperation, { plugin: 'plugin-ts' })

    expect(resolveFile(ctx, shapePoint, { plugin: 'plugin-ts' }).path).toBe('/root/src/gen/types/pointOperation.ts')
  })

  it('uses the plugin output banner and footer', () => {
    const ctx = createContext({
      options: { output: { path: 'zod', mode: 'directory', banner: '// banner', footer: (meta: { title?: string }) => `// ${meta.title}` } },
    } as Partial<FileContext>)
    const target = resolveFile(ctx, point)

    expect(target.banner).toBe('// banner')
    expect(target.footer).toBe('// Pet Store')
  })

  it('names the file after the name option', () => {
    expect(resolveFile(createContext(), listPets, { name: 'listPetsQuery' }).baseName).toBe('listPetsQuery.ts')
  })

  it('throws for a schema without a name', () => {
    expect(() => resolveFile(createContext(), ast.factory.createSchema({ type: 'string' }))).toThrow(
      expect.objectContaining({ diagnostic: expect.objectContaining({ code: Diagnostics.code.pluginFailed }) }),
    )
  })

  it('reads the current context as a composable', () => {
    const ctx = createContext()

    expect(withContext(ctx as never, () => file(point))).toStrictEqual(resolveFile(ctx, point))
  })

  it('reports KUBB_NO_CONTEXT outside a generator', () => {
    const call = () => withContext({ plugin: { name: 'plugin-zod' } } as never, () => file(point))

    expect(call).toThrow(expect.objectContaining({ diagnostic: expect.objectContaining({ code: Diagnostics.code.noContext }) }))
  })
})
