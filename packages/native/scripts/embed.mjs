// Embeds the built wasm as base64 so the package ships one JavaScript file that bundlers never have to copy a binary for.
import { readFileSync, writeFileSync } from 'node:fs'

const wasm = readFileSync(new URL('../crate/target/wasm32-unknown-unknown/release/kubb_native.wasm', import.meta.url))
const header = '// Generated by `pnpm build:native` from crate/src/lib.rs. Do not edit.'
writeFileSync(new URL('../src/wasm.ts', import.meta.url), `${header}\nexport default '${wasm.toString('base64')}'\n`)
