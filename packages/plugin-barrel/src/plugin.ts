import path from 'node:path'
import { isPathInside, toPosixPath } from '@internals/utils'
import { defineExtension } from '@kubb/core'
import { ast, Diagnostics } from '@kubb/kit'
import type { Config, NormalizedPlugin, Plugin } from '@kubb/kit'
import { compatibility } from '../kubb-extension.json'
import { version } from '../package.json'
import type { BarrelType, PluginBarrelConfig } from './types.ts'
import { buildBarrelIndex, getBarrelFiles } from './utils.ts'

/**
 * Applies a plugin's configured `output.banner`/`footer` to a barrel file, flagged as `isBarrel`.
 *
 * Resolves through the plugin's own resolver, and only when the plugin explicitly sets a
 * banner/footer, so barrels stay banner-free by default and never inherit the implicit
 * "Generated by Kubb" notice.
 */
function withBarrelBannerFooter({ file, plugin, config }: { file: ast.FileNode; plugin: NormalizedPlugin; config: Config }): ast.FileNode {
  const output = plugin.options?.output
  const resolver = plugin.resolver
  const hasBanner = output?.banner !== undefined
  const hasFooter = output?.footer !== undefined
  if (!resolver || (!hasBanner && !hasFooter)) return file

  const context = { output, config, file: { path: file.path, baseName: file.baseName, isBarrel: true } }
  return {
    ...file,
    banner: hasBanner ? resolver.default.banner(undefined, context) : file.banner,
    footer: hasFooter ? resolver.default.footer(undefined, context) : file.footer,
  }
}

/**
 * Canonical plugin name for `@kubb/plugin-barrel`. Used for driver lookups
 * and to guard the `kubb:plugin:end` handler against reacting to its own lifecycle hook.
 */
export const pluginBarrelName = 'plugin-barrel' satisfies Plugin['name']

type PendingBarrel = {
  plugin: NormalizedPlugin
  target: string
  barrelType: BarrelType
  nested: boolean
  namespace: boolean
}

type BarrelState = {
  excludedPlugins: Set<string>
  // Subdirectories of `barrel: false` plugins, for files without a `meta.pluginName` owner.
  excludedTargets: Array<string>
  pendingBarrels: Array<PendingBarrel>
}

// One state per build, keyed by the build's `config`. The object form has no factory closure to hold it.
const states = new WeakMap<Config, BarrelState>()

function getState(config: Config): BarrelState {
  const state = states.get(config) ?? { excludedPlugins: new Set(), excludedTargets: [], pendingBarrels: [] }
  states.set(config, state)
  return state
}

/**
 * Generates an `index.ts` for every plugin output directory and one root
 * barrel at `config.output.path/index.ts` after the build completes. Ships
 * with Kubb and is registered by default in `defineConfig`, but generates
 * nothing until a barrel is configured.
 *
 * Each plugin inherits `output.barrel` from `config.output.barrel` (which
 * defaults to `false`, no barrel). Set `barrel: { type: 'named' | 'all' }` on
 * the root config, a plugin, or both to opt in; a plugin-level `false`
 * overrides an enabled root barrel and also excludes that plugin's files
 * from the root barrel.
 *
 * A plugin with `output.mode: 'file'` gets no per-plugin barrel, since its output
 * is a single file. The root barrel re-exports that file directly.
 *
 * @example
 * ```ts
 * import { defineConfig } from '@kubb/core'
 * import { pluginBarrel } from '@kubb/plugin-barrel'
 * import { pluginTs } from '@kubb/plugin-ts'
 * import { pluginZod } from '@kubb/plugin-zod'
 *
 * export default defineConfig({
 *   input: './petStore.yaml',
 *   output: { path: 'src/gen', barrel: { type: 'named' } },
 *   plugins: [
 *     pluginTs({ output: { path: 'types', barrel: { type: 'all' } } }),
 *     pluginZod({ output: { path: 'schemas' } }),
 *     pluginBarrel(),
 *   ],
 * })
 * ```
 */
export const pluginBarrel = defineExtension({
  kind: 'plugin',
  meta: { name: pluginBarrelName, version, compatibility, issues: 'https://github.com/kubb-labs/kubb/issues' },
  enforce: 'post',
  hooks: {
    'kubb:plugin:end'({ plugin, config }) {
      // Skip reactions to the barrel plugin's own lifecycle hook
      if (plugin.name === pluginBarrelName) return

      const { excludedPlugins, excludedTargets, pendingBarrels } = getState(config)

      // A plugin-level `false` wins over an enabled root barrel.
      const barrelConfig: PluginBarrelConfig | false = plugin.options.output?.barrel ?? config.output.barrel ?? false
      const base = path.resolve(config.root, config.output.path)
      const target = path.resolve(base, plugin.options.output.path ?? '.')

      if (barrelConfig === false) {
        excludedPlugins.add(plugin.name)
        // The output root holds every plugin's files, so there only the owner match applies.
        if (target !== base && isPathInside(target, base)) {
          excludedTargets.push(target)
        }
        return
      }

      // A plugin at the output root (no own `output.path`) gets no per-plugin barrel, which would
      // claim every other plugin's directory. The root barrel picks up its files.
      if (target === base) {
        return
      }

      // `mode: 'file'` writes a single file, so there is no directory to barrel. The root barrel
      // re-exports that file as a direct leaf of `config.output.path`.
      if (plugin.options.output.mode === 'file') {
        return
      }

      if (!isPathInside(target, base)) {
        throw new Diagnostics.Error({
          code: Diagnostics.code.pathTraversal,
          severity: 'error',
          message: `Output path "${plugin.options.output.path}" of plugin "${plugin.name}" resolves outside the output directory "${base}".`,
          help: 'Keep the plugin `output.path` within `config.output.path`.',
          location: { kind: 'config' },
        })
      }

      // Only the target directory and barrel strategy are recorded here. The actual file-set
      // scan and directory-tree build happen once, in `kubb:plugins:end`, and are shared by
      // every plugin barrel plus the root barrel instead of repeating per plugin.
      pendingBarrels.push({ plugin, target, barrelType: barrelConfig.type, nested: barrelConfig.nested ?? false, namespace: barrelConfig.namespace ?? false })
    },
    'kubb:plugins:end'({ files, config, upsertFile }) {
      const { excludedPlugins, excludedTargets, pendingBarrels } = getState(config)
      const rootBarrelConfig = config.output.barrel ?? false
      const outputPath = path.resolve(config.root, config.output.path)

      // A `barrel: false` plugin gets no barrel and stays out of the root, so drop its files
      // once here. Every barrel below then derives from a single index of what remains.
      const relevantFiles = files.filter((file) => {
        const owner = (file.meta as { pluginName?: string } | undefined)?.pluginName
        if (owner) return !excludedPlugins.has(owner)

        return !excludedTargets.some((target) => isPathInside(file.path, target))
      })
      excludedPlugins.clear()
      excludedTargets.length = 0

      const index = buildBarrelIndex(outputPath, relevantFiles)
      const reportedCollisions = new Set<string>()
      // Keyed by path and name: plugins sharing an `output.path` produce the same aliases.
      const namespaceExports = new Map<string, ast.ExportNode>()

      pendingBarrels.forEach(({ plugin, target, barrelType, nested, namespace }) => {
        getBarrelFiles({ index, targetPath: target, barrelType, nested, namespace, recursive: true, reportedCollisions }).forEach((file) => {
          upsertFile(withBarrelBannerFooter({ file, plugin, config }))
          if (file.path !== `${toPosixPath(target)}/index.ts`) return
          file.exports
            .filter((item) => item.asAlias)
            .forEach((item) => {
              const itemPath = `./${toPosixPath(path.relative(outputPath, path.resolve(target, item.path)))}`
              namespaceExports.set(`${itemPath}\0${item.name}`, ast.factory.createExport({ ...item, path: itemPath }))
            })
        })
      })
      pendingBarrels.length = 0

      if (rootBarrelConfig === false) return

      getBarrelFiles({ index, barrelType: rootBarrelConfig.type, additionalExports: [...namespaceExports.values()], reportedCollisions }).forEach((file) => {
        upsertFile(file)
      })
    },
  },
})
